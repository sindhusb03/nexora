import { renderTextPdf, type PdfTextRow } from "../src/imports/text-pdf.js";
import { writeXlsx, type XlsxCell } from "../src/imports/xlsx-write.js";

export type HeldScale = "units" | "thousands" | "millions" | "lakhs" | "crores";
export type HeldStatement = "income_statement" | "balance_sheet" | "bank";

export interface HeldCell {
  readonly label: string;
  readonly amount: string;
  readonly statementType: HeldStatement;
  readonly periodStart: string;
  readonly periodEnd: string;
  readonly scale: HeldScale;
  readonly currency: string | null;
  readonly accountCode: string | null;
  readonly autoAccept: boolean;
  readonly txnDate?: string;
  readonly balanceKind?: "opening" | "closing" | "movement";
}

export interface HeldDoc {
  readonly id: string;
  readonly fileName: string;
  readonly bytes: Uint8Array;
  readonly cells: readonly HeldCell[];
}

function csv(rows: readonly (readonly string[])[]): Uint8Array {
  const encoded = rows
    .map((row) =>
      row.map((cell) => (/[",\n]/.test(cell) ? `"${cell.replace(/"/g, '""')}"` : cell)).join(","),
    )
    .join("\n");
  return new TextEncoder().encode(`${encoded}\n`);
}

function grid(rows: readonly (readonly string[])[]): XlsxCell[] {
  const cells: XlsxCell[] = [];
  rows.forEach((row, rowIndex) => {
    row.forEach((value, colIndex) => {
      if (value.length === 0) return;
      const numeric = /^-?\d+(\.\d+)?$/.test(value) && !/^(19|20)\d{2}$/.test(value);
      cells.push({
        row: rowIndex + 1,
        col: colIndex + 1,
        value,
        kind: numeric ? "number" : "string",
      });
    });
  });
  return cells;
}

function pdfRow(items: readonly (readonly [number, string])[]): PdfTextRow {
  return { items: items.map(([x, text]) => ({ x, text })) };
}

function line(
  label: string,
  amount: string,
  statementType: HeldStatement,
  periodStart: string,
  periodEnd: string,
  scale: HeldScale,
  currency: string | null,
  accountCode: string | null,
  autoAccept: boolean,
): HeldCell {
  return {
    label,
    amount,
    statementType,
    periodStart,
    periodEnd,
    scale,
    currency,
    accountCode,
    autoAccept,
  };
}

function bank(
  label: string,
  amount: string,
  periodStart: string,
  periodEnd: string,
  currency: string,
  txnDate: string,
  balanceKind: "opening" | "closing" | "movement",
): HeldCell {
  return {
    label,
    amount,
    statementType: "bank",
    periodStart,
    periodEnd,
    scale: "units",
    currency,
    accountCode: null,
    autoAccept: false,
    txnDate,
    balanceKind,
  };
}

